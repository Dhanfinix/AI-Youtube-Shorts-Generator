"""Dispatches rendered YouTube shorts directly to Telegram."""
import os
import glob
import json
import sys
import requests

def send_telegram():
    bot_token = os.getenv("TELEGRAM_BOT_TOKEN")
    chat_id = os.getenv("TELEGRAM_CHAT_ID")

    if not bot_token or not chat_id:
        print("[telegram] Error: TELEGRAM_BOT_TOKEN or TELEGRAM_CHAT_ID not set.", file=sys.stderr)
        return False

    search_pattern = os.path.join("output", "**", "shorts", "*.mp4")
    clips = glob.glob(search_pattern, recursive=True)

    if not clips:
        print("[telegram] No clips found in output/**/shorts/*.mp4", file=sys.stderr)
        msg_url = f"https://api.telegram.org/bot{bot_token}/sendMessage"
        requests.post(msg_url, data={
            "chat_id": chat_id,
            "text": "⚠️ YouTube Shorts Clipper finished, but no clips were rendered."
        })
        return False

    print(f"[telegram] Found {len(clips)} clip(s) to send to Telegram.", flush=True)

    success_count = 0
    for idx, clip_path in enumerate(clips, 1):
        filename = os.path.basename(clip_path)
        base = os.path.splitext(clip_path)[0]
        json_meta = base + "_metadata.json"

        title = os.path.splitext(filename)[0].replace("_", " ").title()
        caption_text = f"🎬 {title}\n"

        if os.path.exists(json_meta):
            try:
                with open(json_meta, "r", encoding="utf-8") as jf:
                    meta = json.load(jf)
                    if meta.get("title"):
                        caption_text = f"🎬 {meta['title']}\n"
                    if meta.get("hook"):
                        caption_text += f"🪝 {meta['hook']}\n"
            except Exception:
                pass

        caption_text += "\n✨ Generated by AI YouTube Shorts Clipper"

        print(f"[telegram] Sending {filename} ({idx}/{len(clips)})...", flush=True)

        url = f"https://api.telegram.org/bot{bot_token}/sendVideo"
        try:
            with open(clip_path, "rb") as vf:
                data = {
                    "chat_id": chat_id,
                    "caption": caption_text[:1024],
                    "supports_streaming": True
                }
                files = {"video": (filename, vf, "video/mp4")}
                res = requests.post(url, data=data, files=files, timeout=300)

            if res.status_code == 200:
                print(f"[telegram] ✅ Sent: {filename}", flush=True)
                success_count += 1
            else:
                print(f"[telegram] ❌ Failed to send {filename}: {res.text}", file=sys.stderr, flush=True)
        except Exception as e:
            print(f"[telegram] ❌ Exception sending {filename}: {e}", file=sys.stderr, flush=True)

    print(f"[telegram] Finished. {success_count}/{len(clips)} clips sent.", flush=True)
    return success_count > 0

if __name__ == "__main__":
    send_telegram()
